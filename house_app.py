def recommend_districts(city, budget, area_min, area_max, weights, commute_place, district_pref):
    """多维评分推荐片区"""
    districts = BEIJING_DISTRICTS if city == "北京" else SHANGHAI_DISTRICTS

    if area_min > 0:
        target_sqm_low = budget / area_max if area_max > 0 else 0
        target_sqm_high = budget / area_min
    else:
        target_sqm_low, target_sqm_high = 0, 99

    scored = []
    for d in districts:
        score = 0
        reasons = []

        # 预算匹配
        try:
            parts = d["均价"].replace("万/㎡", "").split("-")
            d_low = float(parts[0])
            d_high = float(parts[1]) if len(parts) > 1 else d_low * 2
        except (ValueError, IndexError):
            d_low, d_high = 0, 99

        if target_sqm_high > 0 and d_low <= target_sqm_high and d_high >= target_sqm_low * 0.7:
            budget_score = 10
            reasons.append("✅ 价格在预算范围内")
        elif target_sqm_high > 0 and d_low <= target_sqm_high * 1.3:
            budget_score = 4
            reasons.append("⚠️ 价格略超预算但仍可考虑")
        else:
            budget_score = 1

        # 多维评分
        dim_scores = {
            "学区": d.get("学区评分", 5),
            "交通": d.get("交通评分", 5),
            "医疗": d.get("医疗评分", 5),
            "公园": d.get("公园评分", 5),
            "购物": d.get("购物评分", 5),
        }

        weighted = sum(dim_scores[k] * weights.get(k, 0) for k in dim_scores)
        # 归一化到 0-60 范围（5个维度 × 最高权重5 × 最高评分10 = 250 max, scale）
        dim_final = weighted / 250 * 60

        score = budget_score + dim_final

        # 找出得分最高的维度作为亮点
        if weights:
            top_dim = max(weights, key=lambda k: dim_scores.get(k, 0) * weights.get(k, 0))
            if dim_scores.get(top_dim, 0) >= 8:
                reasons.append(f"🏆 {top_dim}评分高（{dim_scores[top_dim]}/10）")

        # 通勤匹配
        if commute_place:
            if commute_place in d.get("交通", "") or commute_place in d.get("特点", ""):
                score += 5
                reasons.append(f"🚇 通勤到「{commute_place}」方便")

        # 片区偏好
        if district_pref and district_pref != "不限" and district_pref in d["片区"]:
            score += 10
            reasons.append("📍 你指定的首选片区")

        scored.append((score, d, reasons))

    scored.sort(key=lambda x: x[0], reverse=True)
    top = [(d, r) for s, d, r in scored if s > 5]
    if not top:
        top = [(d, ["综合条件可作为备选"]) for _, d, _ in scored[:3]]
    return top[:5]


