def calc_tax(city, total_price, area, house_age, buyer_type, seller_status, house_type):
    P = BEIJING_POLICY if city == "北京" else SHANGHAI_POLICY
    result = {}

    # 契税
    if buyer_type == "首套":
        rate = P["契税"]["首套"]["<=90"] if area <= 90 else P["契税"]["首套"][">90"]
        basis = f"首套{'≤90㎡' if area <= 90 else '>90㎡'}"
    else:
        rate = P["契税"]["二套"]
        basis = "二套统一税率"
    result["契税"] = {"金额": total_price * rate, "税率": f"{rate*100:.1f}%", "依据": f"{basis}", "承担方": "买方"}

    # 增值税
    vat_age = P["增值税"]["免征年限"]
    vat_rate = P["增值税"]["税率"]
    if house_age >= vat_age:
        result["增值税"] = {"金额": 0, "税率": f"{vat_rate*100:.1f}%", "依据": f"房龄{house_age}年≥{vat_age}年，免征", "承担方": "卖方"}
    else:
        result["增值税"] = {"金额": total_price * vat_rate, "税率": f"{vat_rate*100:.1f}%",
                           "依据": f"房龄{house_age}年<{vat_age}年，全额征收", "承担方": "卖方"}

    # 个税
    if seller_status == "满五唯一":
        result["个人所得税"] = {"金额": 0, "税率": "1%（或差额20%）", "依据": "满五唯一免征", "承担方": "卖方"}
    else:
        result["个人所得税"] = {"金额": total_price * P["个税"]["税率"], "税率": "1%",
                               "依据": f"{seller_status}，按总价1%征收", "承担方": "卖方"}

    # 中介费
    result["中介费"] = {"金额": total_price * P["中介费"], "税率": f"{P['中介费']*100:.1f}%",
                       "依据": f"{city}市场行情，通常买卖双方各付一半", "承担方": "买卖双方协商"}

    # 土地出让金
    land_rate = P.get(f"土地出让金_{house_type}", 0)
    if land_rate > 0:
        result["土地出让金"] = {"金额": total_price * land_rate, "税率": f"{land_rate*100:.0f}%",
                               "依据": f"{house_type}需补缴", "承担方": "卖方"}
    else:
        result["土地出让金"] = {"金额": 0, "税率": "0%", "依据": f"{house_type}不涉及", "承担方": "——"}

    numeric = [v["金额"] for v in result.values() if isinstance(v["金额"], (int, float))]
    result["总费用合计"] = {"金额": sum(numeric)}

    dp_rate = P["首付比例"][buyer_type]
    result["首付与贷款"] = {"首付": total_price * dp_rate, "贷款": total_price * (1 - dp_rate),
                           "首付比例": f"{dp_rate*100:.0f}%",
                           "说明": f"{city} {buyer_type}最低首付，非普宅可能上浮"}
    return result


